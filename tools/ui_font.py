def glyph(char):
    """Linhas do glifo (8 linhas) e linhas acima da célula, para acentos de maiúsculas."""
    above = []
    if char in SPECIAL:
        rows = SPECIAL[char].split("|")
    elif char in COMPOSED:
        base, accent = COMPOSED[char]
        rows = GLYPHS[base].split("|")
        mark = ACCENTS[accent]
        if base.isupper():
            above = mark
        else:
            rows = [mark[0], mark[1]] + rows[2:]
    elif char in GLYPHS:
        rows = GLYPHS[char].split("|")
    else:
        rows = "#####|#...#|#...#|#...#|#...#|#...#|#####".split("|")
    width = max(len(row) for row in rows)
    rows = [row.ljust(width, ".") for row in rows] + ["." * width] * (8 - len(rows))
    return rows, above


def advance(char):
    """Avanço do caractere, com 1 pixel de espaço; igual a `glyph_width` da prévia em Rust."""
    if char == " ":
        return 4
    rows, _ = glyph(char)
    return len(rows[0]) + 1
