"""Build small spatial sound variants from licensed CC0 recordings (requires ffmpeg).
Runtime/build of the mod uses the checked-in OGGs, not ffmpeg or source downloads.
"""
import array
import hashlib
import json
import math
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / 'tools/machine_audio.json'
SOURCES = ROOT / 'third_party/audio/kenney'
ASSETS = ROOT / 'content/assets/veio'
RATE = 22050


def add_labels(languages):
    for name, event in json.loads(CONFIG.read_text()).get('events').items():
        for code, text in [('pt_br', event['pt']), ('en_us', event['en'])]:
            languages[code]['subtitles.veio.machine.' + name] = text


def build():
    config = json.loads(CONFIG.read_text())
    provenance = json.loads((SOURCES / 'SOURCES.json').read_text())
    output = ASSETS / 'sounds/machines'
    output.mkdir(parents=True, exist_ok=True)
    registry = {}
    for name, event in config['events'].items():
        variants = []
        for index, filename in enumerate(event['files']):
            source = SOURCES / event['pack'] / filename
            assert hashlib.sha256(source.read_bytes()).hexdigest() == provenance[event['pack']]['members'][filename], source
            # Cut original recordings; gentle bandwidth reduction keeps the small,
            # dry sounds close to Minecraft's block feedback rather than loud music.
            filters = (f"atrim=start={event['start']}:duration={event['duration']},asetpts=PTS-STARTPTS,"
                       f"aresample={RATE},asetrate={int(RATE * event['rate'])},aresample={RATE},highpass=f=100,lowpass=f={event.get("lowpass",4500)}")
            decoded = subprocess.check_output(['ffmpeg', '-v', 'error', '-i', str(source), '-ac', '1', '-ar', str(RATE),
                                                '-af', filters, '-f', 's16le', '-'])
            samples = array.array('h', decoded)
            # Arrange repeated mechanical impacts, never synthesize tones or music.
            mixed = [0] * round(RATE * event['duration'])
            for beat in event['beats']:
                offset = round(beat * RATE)
                for i, value in enumerate(samples[:len(mixed)-offset]):
                    mixed[i+offset] += value
            peak = max(map(abs, mixed), default=1) or 1
            gain = min(4, 16384 / peak)
            if event.get('ambient'):
                rms = math.sqrt(sum(v*v for v in mixed) / len(mixed)) or 1
                gain = min(gain, 32768 * .10 / rms)
            fade_in = event.get('fade', .012)
            fade_out = event.get('fade', .07)
            faded = array.array('h', (round(v * gain * min(1, i/(RATE*fade_in), (len(mixed)-1-i)/(RATE*fade_out)))
                                    for i, v in enumerate(mixed)))
            path = output / f'{name}_{index}.ogg'
            subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 's16le', '-ar', str(RATE), '-ac', '1', '-i', '-',
                            '-c:a', 'libvorbis', '-q:a', '3', '-map_metadata', '-1', str(path)], input=faded.tobytes(), check=True)
            variants.append(dict(name=f'veio:machines/{name}_{index}', attenuation_distance=8))
        registry['machine.'+name] = dict(subtitle='subtitles.veio.machine.'+name, sounds=variants)
    (ASSETS / 'sounds.json').write_text(json.dumps(registry, indent=2)+'\n')
    generated = ['// @generated by tools/build_machine_audio.py; edit tools/machine_audio.json.',
                 'use super::Profile;', 'pub(super) fn profile(block: &str) -> Option<Profile> {', '    Some(match block {']
    for family, p in enumerate(config['profiles']):
        blocks = ' | '.join('"veio:'+block+'"' for block in p['blocks'])
        event = lambda k: 'Some("veio:machine.'+p[k]+'")' if p[k] else 'None'
        generated.append(f'        {blocks} => Profile {{ family: {family}, work: {event("work")}, finish: {event("finish")}, interval: {p["interval"]}, volume: {p["volume"]}, ambient: {str(p["ambient"]).lower()} }},')
    generated += ['        _ => return None,', '    })', '}']
    target = ROOT / 'native/api/src/soundscape/data.rs'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text('\n'.join(generated)+'\n')
    langs = {code: json.loads((ASSETS / f'lang/{code}.json').read_text()) for code in ['pt_br', 'en_us']}
    add_labels(langs)
    for code, data in langs.items():
        (ASSETS / f'lang/{code}.json').write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')
    print(f'Built {len(registry)} sound events / {sum(len(e["sounds"]) for e in registry.values())} mono variants')


if __name__ == '__main__':
    build()
